"""The real verification run (DEVELOPMENT.md §12): throwaway venv → install → smoke.

Isolation level is an ephemeral venv in the system temp directory — clean and
disposable, but **not** a sandbox. The user's real environments are never touched;
a fingerprint of the running interpreter's package set is taken before and after
as a fuse (§22-8).
"""

from __future__ import annotations

import hashlib
import json
import os
import shutil
import tempfile
import time
from collections.abc import Callable
from dataclasses import dataclass, field
from pathlib import Path

import httpx

from envdoctor.domain.enums import CheckpointState
from envdoctor.domain.models import Checkpoint
from envdoctor.paths import RunLayout
from envdoctor.subproc import run_command
from envdoctor.verify.planner import VerifyPlan
from envdoctor.verify.scripts import DEVICE_SCRIPT, MINIMAL_MODEL_SCRIPT

UV_MISSING_REASON = "未找到 uv；真实验证依赖 uv 创建一次性环境（安装说明：https://docs.astral.sh/uv/）"
DEFAULT_INDEX = "https://pypi.org/simple"
COVERED_FRAMEWORKS = {"torch", "tensorflow", "jax"}


@dataclass
class VerifyResult:
    checkpoints: list[Checkpoint] = field(default_factory=list)
    env_dir: str | None = None
    requirements_path: str | None = None
    note: str | None = None


def user_env_fingerprint() -> str:
    import importlib.metadata as metadata

    entries = sorted(f"{dist.metadata['Name']}=={dist.version}" for dist in metadata.distributions())
    return hashlib.sha256("\n".join(entries).encode("utf-8")).hexdigest()[:16]


def venv_python_path(env_dir: str) -> str:
    windows = Path(env_dir) / "Scripts" / "python.exe"
    if windows.exists():
        return str(windows)
    return str(Path(env_dir) / "bin" / "python")


def check_reachability(url: str, *, timeout_s: float = 5.0) -> bool:
    try:
        response = httpx.get(url, timeout=timeout_s, follow_redirects=True, headers={"User-Agent": "envdoctor"})
        return response.status_code < 500
    except httpx.HTTPError:
        return False


def _last_meaningful_line(text: str, *, limit: int = 160) -> str:
    for line in reversed(text.strip().splitlines()):
        if line.strip():
            return line.strip()[:limit]
    return ""


def _parse_json_output(text: str) -> dict | None:
    for line in reversed(text.strip().splitlines()):
        stripped = line.strip()
        if stripped.startswith("{"):
            try:
                payload = json.loads(stripped)
            except json.JSONDecodeError:
                continue
            if isinstance(payload, dict):
                return payload
    return None


class VerifyRunner:
    def __init__(
        self,
        *,
        run: RunLayout,
        plan: VerifyPlan,
        uv_path: str | None,
        runner=run_command,
        reachability=check_reachability,
        echo: Callable[[str], None] | None = None,
    ) -> None:
        self._run = run
        self._plan = plan
        self._uv = uv_path
        self._runner = runner
        self._reachability = reachability
        self._echo = echo or (lambda _message: None)

    # -- helpers ---------------------------------------------------------------

    def _write_log(self, checkpoint_id: str, text: str) -> str:
        path = self._run.log_path(checkpoint_id)
        path.write_text(text if text.endswith("\n") else text + "\n", encoding="utf-8", newline="\n")
        return str(path)

    def _write_requirements(self) -> Path:
        interpreter = self._plan.interpreter
        header = [
            f"# generated by envdoctor from: {self._plan.requirements_source}",
            f"# target interpreter: {interpreter.version if interpreter else 'unknown'}",
        ]
        path = self._run.requirements_path
        path.write_text("\n".join(header + self._plan.requirement_lines) + "\n", encoding="utf-8", newline="\n")
        return path

    @staticmethod
    def _skip(checkpoint_id: str, title: str, reason: str) -> Checkpoint:
        return Checkpoint(id=checkpoint_id, title=title, state=CheckpointState.SKIP, skip_reason=reason)

    # -- steps -----------------------------------------------------------------

    def _run_venv(self, env_dir: str) -> Checkpoint:
        assert self._uv is not None
        assert self._plan.interpreter is not None
        result = self._runner(
            [self._uv, "venv", "--python", self._plan.interpreter.path, env_dir],
            timeout_s=60.0,
        )
        log_path = self._write_log(
            "venv", f"$ uv venv --python {self._plan.interpreter.path} {env_dir}\n\n{result.tail(40)}"
        )
        if result.ok and Path(venv_python_path(env_dir)).exists():
            return Checkpoint(
                id="venv",
                title="创建临时环境（uv venv）",
                state=CheckpointState.PASS,
                seconds=result.seconds,
                detail=f"{self._plan.interpreter.version} → {env_dir}",
                log_path=log_path,
            )
        detail = _last_meaningful_line(result.stderr) or result.error or f"退出码 {result.returncode}"
        return Checkpoint(
            id="venv",
            title="创建临时环境（uv venv）",
            state=CheckpointState.ERROR if result.timed_out else CheckpointState.FAIL,
            seconds=result.seconds,
            detail=detail,
            log_path=log_path,
        )

    def _run_install(self, env_dir: str, requirements_path: Path) -> Checkpoint:
        assert self._uv is not None
        index = self._plan.primary_index or DEFAULT_INDEX
        if not self._reachability(index):
            return Checkpoint(
                id="install",
                title="安装依赖（uv pip install）",
                state=CheckpointState.SKIP,
                skip_reason=f"安装源不可达（预检失败）：{index}",
                detail=(
                    "可用 --index-url 指定可达镜像（例如清华镜像 https://pypi.tuna.tsinghua.edu.cn/simple），"
                    "或在 envdoctor.toml 配置 defaults.index_url"
                ),
            )
        argv = [
            self._uv,
            "pip",
            "install",
            "--python",
            venv_python_path(env_dir),
            "-r",
            str(requirements_path),
        ]
        if self._plan.primary_index:
            argv += ["--index-url", self._plan.primary_index]
        for extra in self._plan.extra_indexes:
            argv += ["--extra-index-url", extra]
        result = self._runner(argv, timeout_s=self._plan.timeout_s)
        log_path = self._write_log("install", f"$ {' '.join(argv)}\n\n{result.tail(200)}")
        if result.ok:
            return Checkpoint(
                id="install",
                title="安装依赖（uv pip install）",
                state=CheckpointState.PASS,
                seconds=result.seconds,
                detail=_last_meaningful_line(result.stderr) or _last_meaningful_line(result.stdout) or "安装完成",
                log_path=log_path,
            )
        detail = _last_meaningful_line(result.stderr) or result.error or f"退出码 {result.returncode}"
        return Checkpoint(
            id="install",
            title="安装依赖（uv pip install）",
            state=CheckpointState.ERROR if result.timed_out else CheckpointState.FAIL,
            seconds=result.seconds,
            detail=detail,
            log_path=log_path,
        )

    def _run_imports(self, env_dir: str) -> Checkpoint:
        if not self._plan.ml_modules:
            return self._skip("imports", "import 冒烟测试", "未检测到需要导入的 ML 库")
        python = venv_python_path(env_dir)
        started = time.perf_counter()
        lines: list[str] = []
        failures: list[str] = []
        passed: list[str] = []
        for package, module in self._plan.ml_modules:
            command = [python, "-c", f"import {module}; print(getattr({module}, '__version__', 'unknown'))"]
            result = self._runner(command, timeout_s=120.0)
            output = (result.stdout or result.stderr).strip()
            mark = "PASS" if result.ok else "FAIL"
            lines.append(f"[{mark}] {package} → import {module}: {_last_meaningful_line(output)}")
            if result.ok:
                passed.append(f"{package} {_last_meaningful_line(output)}")
            else:
                failures.append(f"{package}: {_last_meaningful_line(output)}")
        log_path = self._write_log("imports", "\n".join(lines))
        seconds = time.perf_counter() - started
        if failures:
            return Checkpoint(
                id="imports",
                title="import 冒烟测试",
                state=CheckpointState.FAIL,
                seconds=seconds,
                detail="；".join(failures[:3]),
                log_path=log_path,
            )
        return Checkpoint(
            id="imports",
            title="import 冒烟测试",
            state=CheckpointState.PASS,
            seconds=seconds,
            detail="；".join(passed[:5]),
            log_path=log_path,
        )

    def _run_generated_script(
        self, env_dir: str, checkpoint_id: str, title: str, script: str
    ) -> tuple[Checkpoint, dict | None]:
        script_path = self._run.dir / f"{checkpoint_id}-script.py"
        script_path.write_text(script, encoding="utf-8", newline="\n")
        result = self._runner([venv_python_path(env_dir), str(script_path)], timeout_s=180.0)
        log_path = self._write_log(checkpoint_id, result.tail(200))
        payload = _parse_json_output(result.stdout)
        if result.ok:
            return (
                Checkpoint(
                    id=checkpoint_id,
                    title=title,
                    state=CheckpointState.PASS,
                    seconds=result.seconds,
                    detail=None,
                    log_path=log_path,
                ),
                payload,
            )
        return (
            Checkpoint(
                id=checkpoint_id,
                title=title,
                state=CheckpointState.ERROR if result.timed_out else CheckpointState.FAIL,
                seconds=result.seconds,
                detail=_last_meaningful_line(result.stderr)
                or _last_meaningful_line(result.stdout)
                or f"退出码 {result.returncode}",
                log_path=log_path,
            ),
            payload,
        )

    def _run_device(self, env_dir: str) -> Checkpoint:
        checkpoint, payload = self._run_generated_script(
            env_dir, "device", "设备检查（框架版本 / CUDA 可用性）", DEVICE_SCRIPT
        )
        if checkpoint.state == CheckpointState.PASS and payload is not None:
            parts: list[str] = []
            if torch_version := payload.get("torch"):
                parts.append(
                    f"torch {torch_version}（cuda={payload.get('torch_cuda')}，"
                    f"available={payload.get('cuda_available')}）"
                )
            if devices := payload.get("devices"):
                parts.append("设备：" + ", ".join(str(item) for item in devices))
            if tf_version := payload.get("tensorflow"):
                parts.append(f"tensorflow {tf_version}（gpus={payload.get('tensorflow_gpus')}）")
            if jax_version := payload.get("jax"):
                parts.append(f"jax {jax_version}（devices={payload.get('jax_devices')}）")
            checkpoint.detail = "；".join(parts) or "未安装 torch / tensorflow / jax，仅确认解释器可执行"
        return checkpoint

    def _run_minimal_model(self, env_dir: str) -> Checkpoint:
        covered = COVERED_FRAMEWORKS & {name for name, _module in self._plan.ml_modules}
        if not covered:
            return self._skip(
                "minimal-model", "最小模型（前向/反向）", "依赖中没有 torch / tensorflow / jax，无最小模型可跑"
            )
        checkpoint, payload = self._run_generated_script(
            env_dir, "minimal-model", "最小模型（前向/反向）", MINIMAL_MODEL_SCRIPT
        )
        if checkpoint.state == CheckpointState.PASS and payload is not None:
            parts = []
            if torch_result := payload.get("torch"):
                parts.append(f"torch device={torch_result.get('device')}")
            if "tensorflow" in payload:
                parts.append("tensorflow 张量运算通过")
            if "jax" in payload:
                parts.append("jax 张量运算通过")
            checkpoint.detail = "；".join(parts) or "通过"
        return checkpoint

    def _run_smoke(self, env_dir: str, index: int, command: str) -> Checkpoint:
        scripts_dir = str(Path(venv_python_path(env_dir)).parent)
        env_extra = {
            "VIRTUAL_ENV": env_dir,
            "PATH": scripts_dir + os.pathsep + os.environ.get("PATH", ""),
        }
        argv = ["cmd", "/c", command] if os.name == "nt" else ["sh", "-c", command]
        result = self._runner(argv, timeout_s=300.0, env_extra=env_extra)
        checkpoint_id = f"smoke-{index}"
        log_path = self._write_log(checkpoint_id, f"$ {command}\n\n{result.tail(200)}")
        if result.ok:
            return Checkpoint(
                id=checkpoint_id,
                title=f"冒烟命令：{command}",
                state=CheckpointState.PASS,
                seconds=result.seconds,
                detail=_last_meaningful_line(result.stdout) or "退出码 0",
                log_path=log_path,
            )
        return Checkpoint(
            id=checkpoint_id,
            title=f"冒烟命令：{command}",
            state=CheckpointState.ERROR if result.timed_out else CheckpointState.FAIL,
            seconds=result.seconds,
            detail=_last_meaningful_line(result.stderr)
            or _last_meaningful_line(result.stdout)
            or f"退出码 {result.returncode}",
            log_path=log_path,
        )

    # -- orchestration ---------------------------------------------------------

    def run_checks(self) -> VerifyResult:
        if self._uv is None:
            return VerifyResult(
                checkpoints=[self._skip("venv", "创建临时环境（uv venv）", UV_MISSING_REASON)],
                note="未找到 uv，已跳过真实验证",
            )
        if self._plan.interpreter is None:
            return VerifyResult(checkpoints=[], note=self._plan.interpreter_reason)
        if not self._plan.installable:
            return VerifyResult(checkpoints=[], note="项目未声明任何可安装的 pip 依赖，跳过真实验证")

        before = user_env_fingerprint()
        env_dir = tempfile.mkdtemp(prefix="envdoctor-verify-")
        requirements_path = self._write_requirements()
        kept_dir: str | None = None
        checkpoints: list[Checkpoint] = []
        try:
            venv_checkpoint = self._run_venv(env_dir)
            checkpoints.append(venv_checkpoint)
            if venv_checkpoint.state == CheckpointState.PASS:
                install_checkpoint = self._run_install(env_dir, requirements_path)
                checkpoints.append(install_checkpoint)
                if install_checkpoint.state == CheckpointState.PASS:
                    imports_checkpoint = self._run_imports(env_dir)
                    checkpoints.append(imports_checkpoint)
                    if imports_checkpoint.state == CheckpointState.PASS:
                        checkpoints.append(self._run_device(env_dir))
                        checkpoints.append(self._run_minimal_model(env_dir))
                    elif imports_checkpoint.state == CheckpointState.SKIP:
                        checkpoints.append(self._skip("device", "设备检查（框架版本 / CUDA 可用性）", "无 ML 库可检查"))
                        checkpoints.append(self._skip("minimal-model", "最小模型（前向/反向）", "无 ML 库可测试"))
                    for index, command in enumerate(self._plan.smoke_cmds, start=1):
                        checkpoints.append(self._run_smoke(env_dir, index, command))
        finally:
            if self._plan.keep_env:
                kept_dir = env_dir
                self._echo(f"临时环境已保留（--keep-env）：{env_dir}")
            else:
                shutil.rmtree(env_dir, ignore_errors=True)

        after = user_env_fingerprint()
        checkpoints.append(
            Checkpoint(
                id="user-env-unchanged",
                title="用户环境未被修改",
                state=CheckpointState.PASS if before == after else CheckpointState.FAIL,
                detail=f"解释器包集合指纹 {before} → {after}",
            )
        )
        return VerifyResult(checkpoints=checkpoints, env_dir=kept_dir, requirements_path=str(requirements_path))
